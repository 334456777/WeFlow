// The WebUI's types of the command API's answers (#399), generated from the contract `weflow-cli` keeps in
// contract/openapi.json: `bun run contract` writes src/api/contract.gen.ts, `bun run contract --check` fails when it
// is not what the contract says (CI runs it). The schemas are those schemars writes for the Rust types, a small part of
// JSON Schema; anything else is refused rather than guessed.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

type Schema = { [key: string]: unknown };

const SOURCE = fileURLToPath(new URL('../contract/openapi.json', import.meta.url));
const TARGET = fileURLToPath(new URL('../src/api/contract.gen.ts', import.meta.url));
const REF = '#/components/schemas/';
/** What a schema may say that does not change its type. */
const NOTES = new Set(['description', 'format', 'minimum', 'maximum', 'examples', 'default', 'title']);

const doc = JSON.parse(readFileSync(SOURCE, 'utf8')) as {
  info: { version: string };
  paths: Record<string, { get: { 'x-weflow-command'?: string; responses: Record<string, { content?: Record<string, { schema: Schema }> }> } }>;
  components: { schemas: Record<string, Schema> };
};

function fail(where: string, why: string): never {
  throw new Error(`contract/openapi.json, ${where}: ${why}`);
}

function name(ref: string, where: string): string {
  if (!ref.startsWith(REF)) fail(where, 'a $ref outside components/schemas: ' + ref);
  const n = ref.slice(REF.length);
  if (!doc.components.schemas[n]) fail(where, 'no schema ' + n);
  return n;
}

const literal = (v: unknown) => JSON.stringify(v);
const key = (k: string) => (/^[A-Za-z_$][\w$]*$/.test(k) ? k : literal(k));

function comment(text: unknown, indent: string): string {
  if (typeof text !== 'string' || !text.trim()) return '';
  const lines = text.trim().replace(/\*\//g, '* /').split('\n');
  return lines.length === 1 ? `${indent}/** ${lines[0]} */\n` : `${indent}/**\n${lines.map(l => `${indent} * ${l}`).join('\n')}\n${indent} */\n`;
}

/** The TypeScript of a schema, `indent` being that of the line it is on. */
function type(s: Schema | boolean, where: string, indent = ''): string {
  // `true` takes any value (a row, a progress event), `false` none
  if (typeof s === 'boolean') return s ? 'unknown' : 'never';
  const known = new Set([...NOTES, 'type', '$ref', 'enum', 'const', 'items', 'properties', 'required', 'anyOf', 'oneOf', 'additionalProperties']);
  for (const k of Object.keys(s)) if (!known.has(k)) fail(where, 'cannot read `' + k + '`');
  if (typeof s.$ref === 'string') return name(s.$ref, where);
  if ('const' in s) return literal(s.const);
  if (Array.isArray(s.enum)) return s.enum.map(literal).join(' | ');
  for (const k of ['anyOf', 'oneOf'] as const) {
    if (Array.isArray(s[k])) return (s[k] as Schema[]).map((x, i) => type(x, `${where}.${k}[${i}]`, indent)).join(' | ');
  }
  const kinds = s.type === undefined ? [] : Array.isArray(s.type) ? s.type : [s.type];
  if (!kinds.length) return 'unknown';
  return kinds.map(kind => {
    switch (kind) {
      case 'string': return 'string';
      case 'integer': case 'number': return 'number';
      case 'boolean': return 'boolean';
      case 'null': return 'null';
      case 'array': {
        if (!s.items || typeof s.items !== 'object') fail(where, 'an array without `items`');
        const item = type(s.items as Schema, where + '.items', indent);
        return /[ |&]/.test(item) ? `(${item})[]` : `${item}[]`;
      }
      case 'object': return object(s, where, indent);
      default: return fail(where, 'cannot read the type ' + literal(kind));
    }
  }).join(' | ');
}

function object(s: Schema, where: string, indent: string): string {
  const properties = (s.properties ?? {}) as Record<string, Schema>;
  // a map (`BTreeMap<String, T>`) says the type of its values here (#430)
  if (typeof s.additionalProperties === 'object') {
    if (Object.keys(properties).length) fail(where, '`additionalProperties` with a schema beside `properties`');
    return `Record<string, ${type(s.additionalProperties as Schema, where + '.additionalProperties', indent)}>`;
  }
  if (!Object.keys(properties).length) {
    if (s.additionalProperties === false) return 'Record<string, never>';
    // a row of WeChat's table: its columns are WeChat's
    return 'Record<string, unknown>';
  }
  const required = new Set((s.required ?? []) as string[]);
  const inner = indent + '  ';
  const lines = Object.entries(properties).map(([k, p]) =>
    comment(p.description, inner) + `${inner}${key(k)}${required.has(k) ? '' : '?'}: ${type(p, `${where}.${k}`, inner)};`);
  return `{\n${lines.join('\n')}\n${indent}}`;
}

function generate(): string {
  const out = [
    '// Generated by scripts/contract.ts from contract/openapi.json (#399); do not edit. `bun run contract` writes it',
    '// again once weflow-cli has rewritten the contract.',
    '',
    `/** The API version of the contract, \`apiVersion\` of \`/health\`. */`,
    `export const CONTRACT_API_VERSION = ${literal(doc.info.version)};`,
  ];
  for (const [n, s] of Object.entries(doc.components.schemas)) {
    const where = 'components.schemas.' + n;
    const body = type(s, where);
    out.push('', comment(s.description, '').trimEnd());
    out.push(body.startsWith('{') ? `export interface ${n} ${body}` : `export type ${n} = ${body};`);
  }
  // the `data` of each command the contract describes, by its name
  const answers: string[] = [];
  for (const [path, item] of Object.entries(doc.paths)) {
    const command = item.get['x-weflow-command'];
    if (!command) continue;
    const ok = item.get.responses['200']?.content?.['application/json']?.schema as Schema | undefined;
    const data = (ok?.properties as Record<string, Schema> | undefined)?.data;
    if (!data) fail(path, 'no `data` in its answer');
    answers.push(comment(data.description, '  ') + `  ${literal(command)}: ${type({ ...data, description: undefined }, path, '  ')};`);
  }
  out.push('', '/** The `data` of the answer of each command the contract describes. */', `export interface Answers {\n${answers.join('\n')}\n}`, '');
  return out.filter((line, i) => line !== '' || out[i - 1] !== '').join('\n').replace(/\n\n\n+/g, '\n\n');
}

const text = generate();
if (process.argv.includes('--check')) {
  let kept = '';
  try { kept = readFileSync(TARGET, 'utf8').replace(/\r\n/g, '\n'); } catch {}
  if (kept !== text) {
    console.error('src/api/contract.gen.ts is not what contract/openapi.json says: run `bun run contract`');
    process.exit(1);
  }
} else {
  writeFileSync(TARGET, text);
}
